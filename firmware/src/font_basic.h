/*
 * Minimal fixed-width bitmap font for the v1 rasterizer (rasterizer.c). Hand-authored
 * for this project — not a transcription of any named/third-party font family, so there
 * is no "did I copy the bytes correctly" risk the way there would be reproducing a
 * well-known font's table from memory.
 *
 * Deliberately narrow scope, matching the rasterizer's v1 scope note (firmware/README.md
 * / the plan for this feature): covers ASCII 0x20 (space) through 0x5A ('Z') — space,
 * common punctuation, digits, and uppercase letters — as one contiguous range with no
 * gaps to index around. Lowercase input is upper-cased at glyph-lookup time in
 * rasterizer.c (the retained text itself keeps its real case — only the glyph choice is
 * affected), so real checklist labels still render legibly without doubling the table.
 * Anything outside this range (rasterizer.c's to_glyph_index() returns 0xFF for it)
 * draws as a small placeholder box instead of silently picking the wrong glyph — except
 * Latin-1 0xB0 (degree sign), which gets its own one-off glyph below (font_glyph_degree)
 * since it's common enough (temperature values) to be worth the one extra entry.
 *
 * Each glyph is 8 rows x 8 columns, MSB-first (bit 7 = leftmost column), glyph pixels
 * confined to columns 0-4 (bits 7-3) so column 5-7 (bits 2-0, always 0 here) provide
 * inter-character spacing at render time. 1 = draw a pixel, 0 = background — rasterizer.c
 * translates that into the panel's own bit=1-white/bit=0-black convention.
 */

